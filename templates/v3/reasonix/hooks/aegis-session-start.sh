#!/usr/bin/env bash
# Aegis 入口注入（Reasonix SessionStart）
# 触发：会话开始 / /new / 清空后新会话
# 作用：把 Aegis 的约束摘要在模型动手前塞进去
#
# 注意：Reasonix 各版本文档对 SessionStart 的 stdout 语义不一致
#（一说无作用，一说注入下一轮上下文）。所以这里只输出内容，不做副作用，
#  注入生效是加分，不生效也无害。

cat <<'EOF'
【AEGIS 入口约束 —— 动手前先看】

1. 先判断「他说的 = 他要的吗」，并说清用了哪个思维模型
   输出格式：我理解你要的是 A / 我判断你真正需要的是 X（依据：<模型>）/ 所以我打算这么做
2. 关键结论标来源：[检索] 有出处 / [推荐] 我推断 / [无参照] 找不到参照
3. 新术语出场时，归到已有概念或标为新增
4. 收尾前更新 NOTES.md：用了什么 / 产出在哪 / 用户明确否定的 / 什么情况说明我错了

收尾自检只看四个字：认知 · 事实 · 语义 · 时间
（详见 CORE-CHECKLIST.md 第 1 层）
EOF
